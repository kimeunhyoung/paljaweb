def fmt(story, message, advice):
    return f"【이 카드의 이야기】\n{story}\n\n【지금 당신에게】\n{message}\n\n【조언】\n{advice}"

def revfmt(story, message, advice):
    return f"【역방향 · 흐림】\n{story}\n\n【지금 당신에게】\n{message}\n\n【조언】\n{advice}"

