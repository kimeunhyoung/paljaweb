function esc(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

function emitObj(name, o) {
  const lines = [`const ${name} = {`];
  const keys = Object.keys(o).sort((a, b) => Number(a) - Number(b));
  for (const k of keys) {
    const { monoRev, dont } = o[k];
    lines.push(`  ${k}: { monoRev: '${esc(monoRev)}', dont: '${esc(dont)}' },`);
  }
  lines.push("};");
  return lines.join("\n");
}

