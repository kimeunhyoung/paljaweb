// 열 기준 순색: R RO O OY Y G GB B Bl I V S (메샤 → 미나)
const BASE = ['#D32F2F', '#E64A19', '#F57C00', '#FFA000', '#FBC02D', '#5FAE2E', '#0097A7', '#1E6FD9', '#2E45B8', '#4338B6', '#8E24AA', '#C2185B'];
const WHITE = [255, 255, 255];
const DARK = [20, 18, 28];
const TINT = [0.80, 0.60, 0.36];
const SHADE = [0.08, 0.20, 0.32, 0.43, 0.52, 0.60];

const hex = (c) => [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));
const mix = (a, b, t) => a.map((v, i) => Math.round(v * (1 - t) + b[i] * t));
const soft = (c, s) => {
  const g = Math.round(0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]);
  return mix(c, [g, g, g], s);
};

function displayColor(col, row) {
  const t = soft(hex(BASE[col]), 0.10);
  return row < 3 ? mix(soft(t, 0.12), WHITE, TINT[row]) : mix(t, DARK, SHADE[row - 3]);
}

