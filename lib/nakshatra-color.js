function canonName(name) {
  const s = String(name || '').trim().replace(/\s+/g, ' ');
  if (NAKSHATRAS.indexOf(s) >= 0) return s;
  return ALIAS[s] || null;
}

function canonBody(body) {
  const s = String(body || '').trim();
  if (PLANET_TEXT[s]) return s;
  const key = BODY_ALIAS[s.toLowerCase()] || BODY_ALIAS[s];
  return key && PLANET_TEXT[key] ? key : null;
}

function nakshatraColor(name, pada, body) {
  const canon = canonName(name);
  const who = canonBody(body);
  const p = Number(pada);
  if (!canon || !(p >= 1 && p <= 4)) {
    throw new Error('낙샤트라 이름이나 파다가 올바르지 않아요: ' + name + ' ' + pada);
  }
  if (!who) throw new Error('행성 이름이 올바르지 않아요: ' + body);
  const n = NAKSHATRAS.indexOf(canon);
  const cell = n * 4 + (p - 1);
  const col = Math.floor(cell / 9);
  const row = cell % 9;
  const tone = toneOf(row);
  const nak = NAK_TEXT[n];
  const isMain = MAIN.indexOf(who) >= 0;
  const text = isMain
    ? [PLANET_TEXT[who], nak[0], nak[1], tone[1]].join(' ')
    : [PLANET_TEXT[who], nak[0]].join(' ');
  return {
    name: canon,
    pada: p,
    col: col,
    row: row,
    rgb: 'rgb(' + displayColor(col, row).join(',') + ')',
    tone: tone[0],
    main: isMain,
    text: text
  };
}

