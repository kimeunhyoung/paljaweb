  function pickSectionKey(ctx) {
    if (!ctx) return 'core';
    if (ctx.curMode === 'energy') return 'core';
    if (ctx.curTopic === 'custom') return 'core';
    if (ctx.curMode === 'question' && ctx.curTopic) {
      return TOPIC_TO_KEY[ctx.curTopic] || 'core';
    }
    return 'core';
  }

  function sectionToAdvice(sec) {
    if (!sec) return '';
    const fact = (sec.summary || '').trim();
    const counsel = (sec.advice || '').trim();
    if (fact && counsel) return '한줄 요약: ' + fact + ' 조언: ' + counsel;
    return counsel || fact || '';
  }

  /**
   * @param {number} cardId 메이저 0–21
   * @param {{ curMode?: string, curTopic?: string, role?: 'normal'|'do'|'dont' }} ctx
   * @returns {{ mainTitle?: string, mono?: string, advice?: string, doDontBody?: string }|null}
   */
  window.getTarotMajorScripted = function (cardId, ctx) {
    const row = CARDS[cardId];
    if (!row) return null;
    const role = (ctx && ctx.role) || 'normal';
    const mainTitle = row.mainTitle || '';

    if (role === 'do' && row.do) {
      return { mainTitle, doDontBody: row.do, mono: row.do };
    }
    if (role === 'dont' && row.dont) {
      return { mainTitle, doDontBody: row.dont, mono: row.dont };
    }

    const key = pickSectionKey(ctx);
    const sec = row[key] || row.core;
    if (!sec || !sec.body) return null;

    return {
      mainTitle,
      mono: sec.body,
      advice: sectionToAdvice(sec),
    };
  };

  window.TAROT_MAJOR_SCRIPTED_IDS = Object.keys(CARDS).map(Number);
